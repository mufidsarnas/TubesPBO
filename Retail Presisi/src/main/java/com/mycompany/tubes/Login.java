    void updateLoginDateTime(String nama,int id) { 
             String sql = "INSERT INTO userlog (nama, dateAktif, idAccount) VALUES (?, ?, ?)";

        try (Connection conn = koneksi.bukaKoneksi();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {
            
            LocalDateTime now = LocalDateTime.now();
            DateTimeFormatter dateAktif = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");
            String formattedDateTime = now.format(dateAktif);

            
            pstmt.setString(1, nama);
            pstmt.setString(2, formattedDateTime);
            pstmt.setInt(3, (id));

            
            pstmt.executeUpdate();
            System.out.println("Login datetime updated successfully.");
        } catch (SQLException e) {
            System.out.println(e.getMessage());
        }
    }




    
