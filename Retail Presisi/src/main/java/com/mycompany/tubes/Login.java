    private void bLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bLoginActionPerformed
        // TODO add your handling code here:
    String sql = "SELECT accountlist.nama, accountlist.idAccount FROM accountlist WHERE accountlist.nama = ? AND accountlist.password = ?";
    try (Connection con = koneksi.bukaKoneksi();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, tfNama.getText());
        pst.setString(2, tfPassword.getText());

        try (java.sql.ResultSet res = pst.executeQuery()) {
            if (res.next()) {
                JOptionPane.showMessageDialog(this, "Berhasil");
                String nama = res.getString("nama");
                int id = res.getInt("idAccount");
                session1.idAccount = id;
                updateLoginDateTime(nama, id);
                dispose();
                menu.main(null);
            } else {
                JOptionPane.showMessageDialog(this, "Gagal");
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_bLoginActionPerformed

